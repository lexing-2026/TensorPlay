"""Kernel signatures of every operator, as C++ function types.

A kernel registered under a dispatch key is called through a pointer cast
to the operator's stub signature, so a kernel whose type differs is
undefined behaviour at the first call.  In-tree kernels are checked when
their registration records its type; an extension (an out-of-tree backend)
gets the same guarantee at compile time from this header:

    m.impl("add.Tensor",
           static_cast<kernel_signatures::add__Tensor*>(&my_add));

``static_cast`` between function pointer types does not compile unless the
two types are identical.  Names replace the overload dot with two
underscores (``add.Tensor`` -> ``add__Tensor``).
"""

from __future__ import annotations

import re

from .api_types import cpp_return_type, stub_arg_type_for
from .model import NativeFunction

# Number of translation units the host fallback tables are split over, so
# the template instantiations compile in parallel.
HOST_FALLBACK_CHUNKS = 8

# Operators a backend must provide itself: the host fallback moves data
# with them (allocation, copies, resizing), or they only rewrite metadata
# and must alias their input.
_HOST_FALLBACK_EXCLUDED_BASES = frozenset({
    "copy_", "_copy_from", "_copy_from_and_resize", "empty", "empty_like",
    "empty_strided", "new_empty", "new_empty_strided", "_to_copy", "to",
    "resize_", "resize_as_", "set_", "set_data", "shallow_copy_data", "item",
    "_local_scalar_dense", "contiguous", "clone", "detach", "detach_", "alias",
    "lift", "lift_fresh", "requires_grad_", "retain_grad", "_version", "data",
    "view", "view_as", "as_strided", "as_strided_", "expand", "expand_as",
    "_unsafe_view", "_reshape_alias", "record_stream",
})

_ALIAS_RETURN = re.compile(r"\([a-z]+\)")


def _symbol(func_name: str) -> str:
    return func_name.replace(".", "__")


def host_fallback_candidates(funcs: list[NativeFunction]) -> list[NativeFunction]:
    """Operators the host fallback may serve: everything that neither
    aliases its input in the result nor belongs to the data-movement set a
    backend implements itself."""
    out: list[NativeFunction] = []
    seen: set[str] = set()
    for f in funcs:
        if f.func_name in seen:
            continue
        seen.add(f.func_name)
        if f.base_name in _HOST_FALLBACK_EXCLUDED_BASES:
            continue
        if f.is_view_op or f.returns_view_of_input:
            continue
        returns = f.schema.split("->", 1)[-1]
        if _ALIAS_RETURN.search(returns):
            continue
        out.append(f)
    return out


def generate_host_fallback_tables(funcs: list[NativeFunction]) -> dict[str, str]:
    """``HostFallbackRegistration_<i>.cpp`` sources, each defining
    ``register_host_fallbacks_<i>(key, count)`` over a slice of the
    candidates."""
    candidates = host_fallback_candidates(funcs)
    files: dict[str, str] = {}
    for chunk in range(HOST_FALLBACK_CHUNKS):
        body = [
            "// Generated by tools/codegen/main.py -- DO NOT EDIT",
            '#include "CpuFallback.h"',
            '#include "tensorplay/ops/KernelSignatures.h"',
            "",
            "namespace tensorplay {",
            "namespace cpu_fallback {",
            "namespace detail {",
            "",
            f"void register_host_fallbacks_{chunk}(DispatchKey key, int& count) {{",
            "    namespace sig = ::tensorplay::kernel_signatures;",
        ]
        for f in candidates[chunk::HOST_FALLBACK_CHUNKS]:
            body.append(
                f'    add_host_fallback<"{f.func_name}", sig::{_symbol(f.func_name)}>(key, count);')
        body += [
            "}",
            "",
            "}  // namespace detail",
            "}  // namespace cpu_fallback",
            "}  // namespace tensorplay",
            "",
        ]
        files[f"HostFallbackRegistration_{chunk}.cpp"] = "\n".join(body)
    return files


def generate_kernel_signatures_header(funcs: list[NativeFunction]) -> str:
    out = [
        "// Generated by tools/codegen/main.py -- DO NOT EDIT",
        "#pragma once",
        "",
        "#include <optional>",
        "#include <tuple>",
        "#include <vector>",
        "",
        '#include "Generator.h"',
        '#include "Storage.h"',
        '#include "Tensor.h"',
        "",
        "namespace tensorplay {",
        "namespace kernel_signatures {",
        "",
    ]
    seen: set[str] = set()
    for f in funcs:
        if f.func_name in seen:
            continue
        seen.add(f.func_name)
        params = ", ".join(
            f"{stub_arg_type_for(f.base_name, a)} {a.name}"
            for a in f.args if a.name != "requires_grad")
        out.append(f"// {f.schema}")
        out.append(f"using {_symbol(f.func_name)} = {cpp_return_type(f)}({params});")
    out += [
        "",
        "}  // namespace kernel_signatures",
        "}  // namespace tensorplay",
        "",
    ]
    return "\n".join(out)
