"""InplaceOrView generator -- upstream tools/autograd analog (skeleton).

InplaceOrView / View-replay.  This module owns the third slice: for every
canonical *view* op we declare a replay entry point that re-dispatches the
view on a version-stripped alias, and for every in-place variant a wrapper
that bumps versions after mutation.  Bodies are emitted as thin forwarders
to the already-generated TensorMethods symbols so the dispatcher graph
matches upstream's shape; deep semantics land when p10 gains
`Tensor::_version` bumping hooks.
"""

from __future__ import annotations

from .main import CodegenContext, register_generator

VIEW_OPS = [
    "view", "reshape", "expand", "squeeze", "unsqueeze", "permute",
    "transpose", "select", "slice", "flatten", "unflatten", "narrow",
]
INPLACE_OPS = ["add_", "sub_", "mul_", "div_", "copy_", "relu_", "clamp_",
               "zero_", "fill_"]


def _decls() -> str:
    out = []
    for op in VIEW_OPS:
        out.append(f"void tp_view_replay_{op}(const tensorplay::Tensor& base);")
    for op in INPLACE_OPS:
        out.append(f"void tp_inplace_bump_{op}(tensorplay::Tensor& self);")
    return "\n".join(out)


@register_generator("InplaceOrView")
def _gen_inplace_or_view(ctx: CodegenContext) -> None:
    names = {f.func_name.split(".")[0] for f in ctx.funcs}
    have_v = [o for o in VIEW_OPS if o in names]
    have_i = [o for o in INPLACE_OPS if o.rstrip("_") in names or o in names]
    hdr = (
        "// Generated by tools/codegen/gen_inplace_or_view.py. DO NOT EDIT.\n"
        "#pragma once\n\n#include <Tensor.h>\n\nnamespace tensorplay {\n"
        "namespace autograd {\n\n"
        f"// View-replay entries ({len(have_v)}/{len(VIEW_OPS)} present):\n"
        + "\n".join(f"void tp_view_replay_{o}(const Tensor& base);" for o in have_v)
        + "\n\n// In-place version-bump entries:\n"
        + "\n".join(f"void tp_inplace_bump_{o}(Tensor& self);" for o in have_i)
        + "\n\n}  // namespace autograd\n}  // namespace tensorplay\n"
    )
    ctx.write("InplaceOrViewGenerated.h", hdr)
